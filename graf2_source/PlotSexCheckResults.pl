use File::Basename;
use lib dirname (__FILE__);

use strict;
use Time::HiRes qw(gettimeofday);
use Getopt::Long;

use SexCheckImage;
use SexCheckResults;

sub errorAndExit
{
    my $msg = shift();
    print "$disclaim\n$usage\n";
    print "\nERROR: ". $msg . "\n\n";

    exit 2;
}

my %opt = ();

my $ret = GetOptions(\%opt,
    "inputFile|in|i=s",
    "outputFile|out|o=s",
    "outSumFile|sum=s",
    "smpSexFile|sf=s",
    "overwrite|fo",
    'graphWidth|gw=i',
    "graphHeight|gh=i",
    "maxBinSmps|ymax=i",
    "maxMaleHetroRate|mhr=f",
    "minFemaleHetroRate|fhr1=f",
    "maxFemaleHetroRate|fhr2=f");

errorAndExit "Must specify input file." if (!$opt{inputFile} || $opt{inputFile} =~ /^-/);
errorAndExit "Input file $opt{inputFile} does not exist." unless -e $opt{inputFile};
errorAndExit "Must specify output file." if (!$opt{outputFile} || $opt{outputFile} =~ /^-/);
errorAndExit "Output file $opt{outputFile} is not a .png file." if $opt{outputFile} !~ /\.png$/i;
errorAndExit "Please specify a valid output file to save the summary." if ($opt{outSumFile} && $opt{outSumFile} =~ /^-/);
errorAndExit "Please specify a valid sample sex file." if ($opt{smpSexFile} && $opt{smpSexFile} =~ /^-/);

my ($sec, $min, $hour, $day, $month, $year, $wday, $yday, $isdst) = localtime;
$year += 1900;
$month += 1;

my $sexCheckRes = new SexCheckResults();
$sexCheckRes->SetParameters(\%opt);

# If smpSexFile is specified, read pheno sexes from this file and overwrites the pheno sex values reported by graf
my $smpSexFile = $opt{smpSexFile} ? $opt{smpSexFile} : "";

my $fileErr = $sexCheckRes->GetSampleSexResults($opt{inputFile}, $smpSexFile);

if ($fileErr) {
    print "\nERROR: $fileErr\n\n";
    exit 2;
}

if ($sexCheckRes->{numFpSmps} < 1) {
    print "\nNOTE: No samples have enough fingerprint SNPs with genotypes to determine sexes.\n\n";
    exit 3;
}

my $sexCheckImage = new SexCheckImage();

$sexCheckImage->SetParameters(\%opt);

my $outputFile = GetOutputFile($opt{outputFile}, $opt{overwrite});
$sexCheckImage->PlotGraph($sexCheckRes, $outputFile, $opt{overwrite});

if ($opt{outSumFile}) {
    my $outSumFile = GetOutputFile($opt{outSumFile}, $opt{overwrite});
    $sexCheckRes->SaveSummary($outSumFile);
}

sub GetOutputFile
{
    my ($outFile, $overwrite) = @_;

    my $newOutFile = $outFile;

    unless ($overwrite) {
	print "\nOutput file $outFile already exists. Overwrite it? (y/n)\n";
	my $ans = <STDIN>;
	if ($ans !~ /^Y/i) {
	    my $base = $outFile;
	    my $ext = "";
	    if ($outFile =~ /(.+)\.(\S+)/) {
		$base = $1;
		$ext = $2;
	    }
	    $newOutFile = sprintf("%s_%04d%02d%02d_%02d%02d", $base, $year, $month, $day, $hour, $min);
	    $newOutFile .= ".$ext" if ($ext);
	}
    }

    return $newOutFile;
}
